#!/usr/bin/env python3
"""Export only the isolated synthetic frontend demo for a static web host.

Run `python scripts/build_demo.py`, then serve dist-demo with an HTTP server.
The output has no Python server, private library, credentials, or live API.
"""
from pathlib import Path
import shutil
import tempfile


def main():
    root = Path(__file__).resolve().parent.parent
    web = root / "web"
    output = root / "dist-demo"
    marker = ".little-archive-demo-build"
    files = ["demo.js", "demo-store.js", "demo-data.js", "app.js", "utils.js", "styles.css", "icon.svg"]
    if output.exists() and not (output / marker).is_file() and any(output.iterdir()):
        raise SystemExit("dist-demo contains unrecognized files; move it aside before building the demo.")
    with tempfile.TemporaryDirectory(prefix=".demo-build-", dir=root) as temporary:
        stage = Path(temporary)
        for name in files:
            shutil.copy2(web / name, stage / name)
        shutil.copy2(web / "demo.html", stage / "index.html")
        (stage / ".nojekyll").write_text("")
        (stage / marker).write_text("Synthetic standalone demo. Generated by scripts/build_demo.py.\n")
        if output.exists():
            shutil.rmtree(output)
        shutil.copytree(stage, output)
    print(f"Built {output} ({len(files) + 3} files). Synthetic demo only; no backend or credentials.")


if __name__ == "__main__":
    main()
